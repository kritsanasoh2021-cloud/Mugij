export function lookupDtcDefinition(code: string): DtcFaultDefinition {
  const normalized = code.trim().toUpperCase();
  const found = HONDA_PGMFI_DTC_LIST.find(
    (d) => d.code.toUpperCase() === normalized || d.obdCode.toUpperCase() === normalized
  );
  if (found) return found;
  return {
    code: normalized,
    milBlink: 'ไม่ระบุ',
    obdCode: normalized,
    titleTh: `รหัสความผิดปกติจาก ECU (${normalized})`,
    titleEn: `Manufacturer Specific Fault (${normalized})`,
    causeTh: 'ตรวจพบสัญญาณผิดปกติในระบบ PGM-FI จากกล่อง ECM',
    fixHintTh: 'ตรวจสอบปลั๊กเซ็นเซอร์และค่า Real-time Sensor ในหน้า Smart Gauge',
    severity: 'warning',
  };
}
